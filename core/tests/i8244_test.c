static int failures;
static int checks;

static void check(int ok, const char *what)
{
    checks++;
    if (!ok)
    {
        printf("FAIL: %s\n", what);
        failures++;
    }
}

#define CHECKF(ok, ...) do { char b_[200]; if (!(ok)) { snprintf(b_, sizeof b_, __VA_ARGS__); check(0, b_); } else checks++; } while (0)

/* The generated test font: the same formula tools/ab/o2ab.py:test_font() uses
 * for the MAME runs. */
static uint8_t g_font[512];

static void make_test_font(void)
{
    for (unsigned i = 0; i < 512; i++)
        g_font[i] = (uint8_t)((i * 2654435761u) >> 24);
}

/* FNV-1a 64 over the XRGB frame as little-endian 32-bit words. */
static uint64_t frame_hash(const uint32_t *f)
{
    uint64_t h = 0xcbf29ce484222325ull;

    for (size_t i = 0; i < (size_t)I8244_WIDTH * I8244_HEIGHT; i++)
        for (int sh = 0; sh < 32; sh += 8)
            h = (h ^ ((f[i] >> sh) & 0xff)) * 0x100000001b3ull;
    return h;
}

/* MAME runs the 8048 a hair faster than 20 (18) pixel clocks a machine cycle:
 * its XTAL class rounds 7.15909 MHz up to 7.1591 MHz for the CPU's clock
 * (5,369,325 Hz; PAL 5,911,500 Hz) and leaves the screen at 7,159,090 Hz.  The
 * goldens carry cycle counts, so the replay uses MAME's ratio (19.999972,
 * 17.999975 pixels), which reproduces MAME's access times to the pixel. */
static uint64_t cyc_to_px(int pal, uint64_t c)
{
    double r = 15.0 * (pal ? 7093790.0 : 7159090.0) / (pal ? 5911500.0 : 5369325.0);

    return (uint64_t)((double)c * r + 0.5);
}

