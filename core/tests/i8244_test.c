typedef struct {
    char kind;          /* 'R' 'W' 'F' */
    uint64_t t;
    unsigned off, data, p1;
} rec_t;

static int load_log(const char *path, rec_t **out, size_t *n)
{
    FILE *f = fopen(path, "r");
    char line[256];
    size_t cap = 4096, cnt = 0;
    rec_t *r = malloc(cap * sizeof *r);

    if (!f || !r)
        return -1;
    while (fgets(line, sizeof line, f))
    {
        rec_t x;
        unsigned long long t;
        unsigned a, b, c;

        memset(&x, 0, sizeof x);
        if (line[0] == 'R' || line[0] == 'W')
        {
            if (sscanf(line + 2, "%llu %u %u %u", &t, &a, &b, &c) != 4)
                continue;
            x.kind = line[0];
            x.t = t;
            x.off = a;
            x.data = b;
            x.p1 = c;
        }
        else if (line[0] == 'P')
        {
            if (sscanf(line + 2, "%llu %u", &t, &a) != 2)
                continue;
            x.kind = 'P';
            x.t = t;
            x.p1 = a;
        }
        else if (line[0] == 'F')
        {
            if (sscanf(line + 2, "%u %llu %u", &a, &t, &c) != 3)
                continue;
            x.kind = 'F';
            x.t = t;
            x.off = a;          /* frame number */
            x.p1 = c;
        }
        else
            continue;
        if (cnt == cap)
        {
            cap *= 2;
            r = realloc(r, cap * sizeof *r);
            if (!r)
                return -1;
        }
        r[cnt++] = x;
    }
    fclose(f);
    *out = r;
    *n = cnt;
    return 0;
}

static int replay_main(int argc, char **argv)
{
    const char *log = NULL, *frames = NULL, *fontp = "test";
    int pal = 0, from = 0, verbose = 0, lum_lead = 0, access_lag = 0;
    rec_t *r = NULL;
    size_t n = 0;
    static i8244_t v;
    static uint8_t realfont[512];
    FILE *ff = NULL;
    static uint32_t md[I8244_WIDTH * I8244_HEIGHT];
    int lag = -1, p17 = 1, bad_frames = 0, bad_reads = 0, nframes = 0, nreads = 0;
    unsigned prev_p1 = 0xff;
    int have_p1_trace = 0;

    for (int i = 2; i < argc; i++)
    {
        if (!strcmp(argv[i], "--replay") && i + 1 < argc) log = argv[++i];
        else if (!strcmp(argv[i], "--frames") && i + 1 < argc) frames = argv[++i];
        else if (!strcmp(argv[i], "--from") && i + 1 < argc) from = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--lag") && i + 1 < argc) lag = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--font") && i + 1 < argc) fontp = argv[++i];
        else if (!strcmp(argv[i], "--lum-lead") && i + 1 < argc) lum_lead = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--access-lag") && i + 1 < argc) access_lag = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--pal")) pal = 1;
        else if (!strcmp(argv[i], "-v")) verbose++;
    }
    log = log ? log : argv[1 < argc ? 1 : 0];
    if (argc > 1 && strcmp(argv[1], "--replay") == 0 && argc > 2)
        log = argv[2];
    make_test_font();
    if (strcmp(fontp, "test"))
    {
        FILE *fp = fopen(fontp, "rb");

        if (!fp || fread(realfont, 1, 512, fp) != 512)
        {
            fprintf(stderr, "cannot read font %s\n", fontp);
            return 2;
        }
        fclose(fp);
    }
    if (!log || load_log(log, &r, &n))
    {
        fprintf(stderr, "cannot read log\n");
        return 2;
    }
    if (frames && !(ff = fopen(frames, "rb")))
    {
        fprintf(stderr, "cannot read frames\n");
        return 2;
    }

    i8244_init(&v, pal, strcmp(fontp, "test") ? realfont : g_font);
    i8244_set_access_lag(&v, (uint64_t)access_lag);

    for (size_t i = 0; i < n && !have_p1_trace; i++)
        have_p1_trace = r[i].kind == 'P';

    for (size_t i = 0; i < n; i++)
    {
        const rec_t *e = &r[i];

        if (e->kind == 'F')
        {
            i8244_run_until(&v, e->t);
            nframes++;
            if (ff)
            {
                long idx = (long)e->off - from - lag;

                if (idx >= 0)
                {
                    long sz = (long)sizeof md;
                    int diffs = 0, fx = -1, fy = -1;

                    fseek(ff, idx * sz, SEEK_SET);
                    if (fread(md, 1, (size_t)sz, ff) == (size_t)sz)
                    {
                        for (int k = 0; k < I8244_WIDTH * I8244_HEIGHT; k++)
                            if ((md[k] & 0xffffff) != (v.frame[k] & 0xffffff))
                            {
                                if (!diffs)
                                {
                                    fx = k % I8244_WIDTH;
                                    fy = k / I8244_WIDTH;
                                }
                                diffs++;
                            }
                        if (diffs)
                        {
                            bad_frames++;
                            if (verbose || bad_frames <= 5)
                                printf("frame %u: %d pixels differ, first at x=%d y=%d (mame %06x, c %06x)\n",
                                       e->off, diffs, fx, fy, md[fy * I8244_WIDTH + fx] & 0xffffff,
                                       v.frame[fy * I8244_WIDTH + fx] & 0xffffff);
                        }
                    }
                }
            }
            continue;
        }

        if (e->kind == 'P')
        {
            /* an exact P1 write (the log was made with VDC_P1TRACE=1) */
            i8244_set_p1_lum(&v, e->t, (int)((e->p1 >> 7) & 1));
            p17 = (int)((e->p1 >> 7) & 1);
            continue;
        }

        /* P17 (LUM): without a trace, the program changed it between the last
         * access and this one; --lum-lead puts it that many pixel clocks
         * before the access (inexact) */
        if (!have_p1_trace && (((e->p1 ^ prev_p1) & 0x80) || ((e->p1 >> 7) & 1) != (unsigned)p17))
        {
            uint64_t tl = e->t > (uint64_t)lum_lead ? e->t - (uint64_t)lum_lead : e->t;

            i8244_set_p1_lum(&v, tl, (int)((e->p1 >> 7) & 1));
            p17 = (int)((e->p1 >> 7) & 1);
        }
        prev_p1 = e->p1;

        if (e->kind == 'W')
        {
            if (!(e->p1 & 0x08))
                i8244_write(&v, e->t, e->off, (uint8_t)e->data);
        }
        else if (!(e->p1 & 0x48))
        {
            uint8_t d = i8244_read(&v, e->t, e->off);
            int ram_selected = !(e->p1 & 0x10) && !(e->off & 0x80);

            if (!ram_selected)
            {
                nreads++;
                if (d != e->data)
                {
                    bad_reads++;
                    if (verbose || bad_reads <= 8)
                        printf("read t=%llu off=$%02X: mame %02X, c %02X\n",
                               (unsigned long long)e->t, e->off, e->data, d);
                }
            }
        }
    }
    printf("%zu records, %d frames, %d bad frames; %d VDC reads, %d bad\n", n, nframes, bad_frames,
           nreads, bad_reads);
    free(r);
    return (bad_frames || bad_reads) ? 1 : 0;
}

