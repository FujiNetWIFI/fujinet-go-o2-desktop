/* absolute time of beam position (vpos, hpos) in the frame that ENDS at
 * frame * F (t = 0 is line 243, pixel 0) */
static uint64_t tvh(int pal, int frame, int v, int h)
{
    const int H = pal ? 456 : 455, V = pal ? 313 : 263;
    const uint64_t F = (uint64_t)H * (uint64_t)V;
    int d = ((v - 243) % V + V) % V;

    return (uint64_t)(frame - 1) * F + (uint64_t)d * (uint64_t)H + (uint64_t)h;
}

static int vb(const i8244_t *v, int pal, int vp, int hp) { return i8244_vblank(v, tvh(pal, 3, vp, hp)); }
static int hb(const i8244_t *v, int pal, int vp, int hp) { return i8244_hblank(v, tvh(pal, 3, vp, hp)); }

static void test_t1_and_beam(void)
{
    static i8244_t n, p;
    int vp, hp;

    i8244_init(&n, 0, g_font);
    i8244_init(&p, 1, g_font);

    /* the beam: t = 0 is the start of VBLANK (line 243) */
    i8244_beam(&n, 0, &vp, &hp);
    check(vp == 243 && hp == 0, "NTSC: the beam is at line 243 pixel 0 at power-on");
    i8244_beam(&n, 20u * 455u, &vp, &hp);
    check(vp == 0 && hp == 0, "NTSC: line 0 comes 20 lines later");
    i8244_beam(&p, 70u * 456u + 17u, &vp, &hp);
    check(vp == 0 && hp == 17, "PAL: line 0 is 70 lines after the start of VBLANK");

    /* NTSC vblank: from (242,365) through (0,365); hblank 366..452 */
    check(!vb(&n, 0, 242, 364) && vb(&n, 0, 242, 365), "NTSC vblank starts at 242:365");
    check(vb(&n, 0, 243, 0) && vb(&n, 0, 262, 454), "NTSC vblank spans lines 243..262");
    check(vb(&n, 0, 0, 365) && !vb(&n, 0, 0, 366) && !vb(&n, 0, 1, 0), "NTSC vblank ends after 0:365");
    check(!hb(&n, 0, 50, 365) && hb(&n, 0, 50, 366) && hb(&n, 0, 50, 452) && !hb(&n, 0, 50, 453), "NTSC hblank 366..452");
    check(i8244_t1(&n, tvh(0, 3, 50, 366)) == 1 && i8244_t1(&n, tvh(0, 3, 50, 100)) == 0 &&
          i8244_t1(&n, tvh(0, 3, 250, 100)) == 1, "T1 = vblank | hblank");
    /* PAL: vblank (242,365) .. (312,365), hblank 366..453 */
    check(!vb(&p, 1, 242, 364) && vb(&p, 1, 242, 365) && vb(&p, 1, 312, 365) && !vb(&p, 1, 312, 366) &&
          !vb(&p, 1, 0, 0), "PAL vblank 242:365 .. 312:365");
    check(hb(&p, 1, 50, 453) && !hb(&p, 1, 50, 454) && !hb(&p, 1, 50, 365), "PAL hblank 366..453");

    /* t1_next_edge against stepping pixel by pixel */
    for (int pal = 0; pal < 2; pal++)
    {
        i8244_t *c = pal ? &p : &n;
        uint64_t F = pal ? 456u * 313u : 455u * 263u;
        int ok = 1;

        for (uint64_t t = 7; t < 2 * F && ok; t += 1237)
        {
            int lvl = i8244_t1(c, t);
            uint64_t e = i8244_t1_next_edge(c, t), s = t + 1;

            while (i8244_t1(c, s) == lvl)
                s++;
            if (e != s)
            {
                ok = 0;
                printf("  t1 edge after %llu: %llu, stepping says %llu (pal %d)\n", (unsigned long long)t,
                       (unsigned long long)e, (unsigned long long)s, pal);
            }
        }
        check(ok, pal ? "PAL: i8244_t1_next_edge agrees with stepping" : "NTSC: i8244_t1_next_edge agrees with stepping");
    }
}

static int g_irq_level, g_irq_calls;
static void irq_cb(void *u, int level) { (void)u; g_irq_level = level; g_irq_calls++; }

static void test_events_and_irq(void)
{
    static i8244_t v;
    const uint64_t F = 455u * 263u;
    uint8_t d;

    i8244_init(&v, 0, g_font);
    i8244_set_irq_callback(&v, irq_cb, NULL);
    g_irq_calls = 0;
    check(!i8244_irq(&v), "no IRQ at power-on");
    check(i8244_next_event(&v) == 20u * 455u, "first event: the screen's scanline 0, 20 lines after the start of VBLANK");
    i8244_run_until(&v, tvh(0, 1, 242, 364));
    check(!i8244_irq(&v), "no vblank IRQ before 242:365");
    i8244_run_until(&v, tvh(0, 1, 242, 365));
    check(i8244_irq(&v) && g_irq_level == 1 && g_irq_calls == 1, "vblank asserts the IRQ at 242:365 (callback once)");
    d = i8244_read(&v, tvh(0, 1, 242, 365) + 50, 0xa1);
    check((d & 0x08) && !i8244_irq(&v) && g_irq_level == 0, "reading $A1 reports vblank and clears the IRQ");
    d = i8244_read(&v, tvh(0, 1, 242, 365) + 60, 0xa1);
    check(!(d & 0x08), "... and clears the sticky bit");
    i8244_run_until(&v, F);
    check(v.frames == 1, "the frame is published at the screen's VBLANK (243:0)");
    i8244_run_until(&v, 3 * F);
    check(v.frames == 3, "three frames in three frame times");
    check(i8244_next_event(&v) > 3 * F, "the next event is in the future");
    /* the status h bit: high on 0xE1 <= x/... the beam at hpos 225..412 on lines <= 242 */
    d = i8244_read(&v, tvh(0, 4, 100, 300), 0xa1);
    check(d & 1, "$A1 bit 0 high at hpos 300 on a visible line");
    d = i8244_read(&v, tvh(0, 4, 100, 100), 0xa1);
    check(!(d & 1), "$A1 bit 0 low at hpos 100");
}

static void test_sound_mix(void)
{
    static i8244_t v;
    static float whole[4000], a[1500], b[2500];
    const uint64_t F = 455u * 263u;
    double sum = 0;
    int ok = 1;
    const float hi = I8244_SOUND_GAIN * 15.0f / 16.0f;

    i8244_init(&v, 0, g_font);
    /* an alternating pattern at the slow clock: one shift every 16 lines, the
     * output toggles every shift */
    i8244_write(&v, 1000, 0xa7, 0xaa);
    i8244_write(&v, 1020, 0xa8, 0xaa);
    i8244_write(&v, 1040, 0xa9, 0xaa);
    i8244_write(&v, 1060, 0xaa, 0x8f);
    i8244_run_until(&v, 8 * F);
    i8244_sound_mix(&v, 0, 8 * F, whole, 4000);
    for (int i = 0; i < 4000; i++)
        sum += whole[i];
    check(sum / 4000 > hi * 0.40f && sum / 4000 < hi * 0.60f, "alternating output averages half of full volume");
    for (int i = 0; i < 4000; i++)
        if (whole[i] < -1e-6f || whole[i] > hi + 1e-6f)
            ok = 0;
    check(ok, "the output is between 0 and the full-volume level (MAME's polarity)");
    /* consuming in two pieces gives the same samples */
    i8244_init(&v, 0, g_font);
    i8244_write(&v, 1000, 0xa7, 0xaa);
    i8244_write(&v, 1020, 0xa8, 0xaa);
    i8244_write(&v, 1040, 0xa9, 0xaa);
    i8244_write(&v, 1060, 0xaa, 0x8f);
    i8244_run_until(&v, 8 * F);
    i8244_sound_mix(&v, 0, 3 * F, a, 1500);
    i8244_sound_mix(&v, 3 * F, 8 * F, b, 2500);
    ok = 1;
    for (int i = 0; i < 1500; i++)
        if (a[i] != whole[i])
            ok = 0;
    for (int i = 0; i < 2500; i++)
        if ((b[i] - whole[1500 + i] > 1e-6f || whole[1500 + i] - b[i] > 1e-6f))
            ok = 0;
    check(ok, "two contiguous mixes equal one");
    check(v.snd_count < 3, "consumed events are pruned");
    /* volume 0 and disabled are silent; volume scales linearly */
    i8244_write(&v, 8 * F + 10, 0xaa, 0x85);
    i8244_run_until(&v, 9 * F);
    i8244_sound_mix(&v, 8 * F, 9 * F, a, 1000);
    {
        double m = 0;

        for (int i = 0; i < 1000; i++)
            m += a[i];
        check(m / 1000 > hi * 5.0f / 15.0f * 0.35f && m / 1000 < hi * 5.0f / 15.0f * 0.65f, "volume 5 is a third of volume 15");
    }
    i8244_write(&v, 9 * F + 10, 0xaa, 0x0f);   /* enable bit clear */
    i8244_run_until(&v, 10 * F);
    i8244_sound_mix(&v, 9 * F + 100, 10 * F, a, 500);
    ok = 1;
    for (int i = 0; i < 500; i++)
        if (a[i] != 0.0f)
            ok = 0;
    check(ok, "sound disabled: silence");
}

static i8244_t *g_cx_chip;
static int g_cx_x;
static void cx_line(void *u, i8244_t *v, int y, int x0, int x1)
{
    (void)u;
    if (y == 100 && x0 <= g_cx_x && g_cx_x <= x1)
        i8244_write_cx(v, g_cx_x, 1);
    /* LUM is the callback's job */
    for (int x = x0; x <= x1; x++)
        v->bitmap[y * I8244_WIDTH + x] |= (uint8_t)i8244_lum(v);
}

static void test_cx_and_line_callback(void)
{
    static i8244_t v;
    const uint64_t F = 455u * 263u;
    uint8_t d;

    i8244_init(&v, 0, g_font);
    g_cx_chip = &v;
    i8244_set_irq_callback(&v, irq_cb, NULL);
    i8244_set_line_callback(&v, cx_line, NULL);
    /* a sprite crossing line 100 at pixel 100.. */
    i8244_write(&v, 100, 0x00, 96);
    i8244_write(&v, 120, 0x01, 45);
    i8244_write(&v, 140, 0x02, 0x08);
    for (int k = 0; k < 8; k++)
        i8244_write(&v, 160 + 20 * (uint64_t)k, 0x80 + (unsigned)k, 0xff);
    i8244_write(&v, 400, 0xa2, 0x40);          /* external overlap in the mask */
    i8244_write(&v, 420, 0xa0, 0x30);          /* fg + external IRQ enable */
    g_cx_x = 102;
    g_irq_calls = 0;
    i8244_run_until(&v, F);                    /* frame 1 renders lines 0..242 */
    i8244_run_until(&v, 2 * F);
    check(g_irq_calls >= 1 && (v.control_status & 0x40), "CX over a drawn object raises the external overlap IRQ and status bit 6");
    check(v.collision_status & 0x01, "... and the sprite's collision bit when it is in the mask (bit 6 mask => sources)");
    d = i8244_read(&v, 2 * F + 1000, 0xa2);
    check(d != 0, "$A2 latched it");
}

static void test_snapshot_and_helpers(void)
{
    static i8244_t v;
    static i8244_snapshot s;
    static uint32_t buf[400 * 300], buf2[400 * 300];
    int w, h;
    char name[64], text[200];

    i8244_init(&v, 0, g_font);
    /* sprite 1: y 50, x 20, colour 5, zoom + S; shape ramp */
    i8244_write(&v, 100, 0x04, 50);
    i8244_write(&v, 120, 0x05, 20);
    i8244_write(&v, 140, 0x06, (5 << 3) | 4 | 2);
    for (int k = 0; k < 8; k++)
        i8244_write(&v, 200 + 20 * (uint64_t)k, 0x88 + (unsigned)k, (uint8_t)((1u << (k + 1)) - 1));
    /* single char 3: y 61 (bit 0 is not connected), x 9, ptr 0x37, colour 0x0d (colour 6, bit8) */
    i8244_write(&v, 500, 0x1c, 61);
    i8244_write(&v, 520, 0x1d, 9);
    i8244_write(&v, 540, 0x1e, 0x37);
    i8244_write(&v, 560, 0x1f, 0x0d);
    /* quad 2: x/y written through char 0 and mirrored for the others */
    i8244_write(&v, 600, 0x60, 100);
    i8244_write(&v, 620, 0x6c, 150);   /* mirror of $60 (y) */
    i8244_write(&v, 640, 0x61, 33);
    i8244_write(&v, 660, 0x69, 34);    /* mirror of $61 */
    i8244_write(&v, 680, 0x62, 0x11);
    i8244_write(&v, 700, 0x66, 0x12);
    i8244_write(&v, 720, 0x6a, 0x13);
    i8244_write(&v, 740, 0x6e, 0x14);
    i8244_write(&v, 760, 0xa3, 0x2a);
    i8244_write(&v, 780, 0xaa, 0xbf);
    i8244_write(&v, 800, 0xa7, 0x0f);
    i8244_write(&v, 820, 0xa8, 0x0f);
    i8244_write(&v, 840, 0xa9, 0x0f);
    i8244_write(&v, 860, 0xe3, 0xa5);
    i8244_write(&v, 880, 0xc2, 0x81);
    i8244_write(&v, 900, 0xd2, 0xff);  /* only bit 0 is connected */
    i8244_write(&v, 920, 0xa0, 0x20 | 0x04 | 0x40 | 0x80);
    i8244_snapshot_get(&v, 1000, &s);

    check(s.sprites[1].y == 50 && s.sprites[1].x == 50 && s.sprites[1].color == 5 && s.sprites[1].zoom == 1 &&
          s.sprites[1].s == 1 && s.sprites[1].x9 == 0, "snapshot: sprite fields");
    check(s.sprites[1].shape[3] == 0x0f && s.sprites[1].width == 32 + 2 && s.sprites[1].height == 32,
          "snapshot: sprite shape and zoomed size (S adds half a bit)");
    check(s.singles[3].y == 60 && s.singles[3].x == 28 && s.singles[3].reg_ptr == 0x37 && s.singles[3].color == 6 &&
          s.singles[3].bit8 == 1, "snapshot: single char (Y bit 0 not connected)");
    check(s.singles[3].rom_offset == ((0x37 | 0x100) + 30) % 512 && s.singles[3].glyph == s.singles[3].rom_offset / 8,
          "snapshot: character ROM position");
    check(s.quads[2].y == 150 && s.quads[2].chars[1].y == 150 && s.quads[2].chars[3].x == (34 + 5) * 2 + 96,
          "snapshot: quad mirrors X/Y and spaces its characters 32 px apart");
    check(s.quads[2].chars[2].reg_ptr == 0x13 && s.quads[2].rows == s.quads[2].chars[0].rows, "snapshot: quad pointers and shared height");
    check(s.control == 0xe4 && s.fg_en && s.dots_en && s.fill && s.sound_irq_en && !s.grid_en && s.lock_objects &&
          !s.lock_grid, "snapshot: control bits and the write lockouts");
    check(s.bg_color == ((0x2a >> 3 & 1) << 2 | (0x2a >> 4 & 1) << 1 | (0x2a >> 5 & 1)) && s.grid_lum == 0 &&
          s.snd_enable && s.snd_fast && s.snd_noise && s.snd_volume == 15, "snapshot: colours and sound bits");
    check(s.shift == 0x0f0f0fu, "snapshot: 24-bit shift register");
    check(s.vgrid[3] == 0xa5 && s.hgrid[2] == 0x181, "snapshot: grid lines (the high byte keeps only bit 0)");
    check(s.shift_clock_hz > 3800 && s.shift_clock_hz < 4000, "snapshot: fast shift clock = line rate / 4");
    {
        /* a non-noise pattern's frequency */
        i8244_write(&v, 1100, 0xaa, 0xaf);
        i8244_snapshot_get(&v, 1200, &s);
        check(s.pattern_period == 8 && s.freq_hz > 480 && s.freq_hz < 495, "snapshot: pattern period and tone frequency (0F0F0F fast: 3933/8 Hz)");
    }
    for (unsigned a = 0; a < 256; a++)
    {
        i8244_describe_register(&v, a, name, sizeof name, text, sizeof text);
        if (!name[0])
        {
            check(0, "every register has a name");
            break;
        }
    }
    checks++;

    /* object bitmaps */
    check(i8244_render_sprite(&v, 1, 2, 0xff000000u, buf, sizeof buf / 4, &w, &h) == 0 && w == 16 && h == 16 &&
          buf[0] == v.palette[8 + 5] && buf[14] == 0xff000000u, "sprite bitmap: 8x8 at scale 2, colour from the register");
    check(i8244_render_sprite(&v, 1, 2, 0, NULL, 0, &w, &h) == 0 && w == 16, "sprite bitmap: size query");
    check(i8244_render_sprite(&v, 1, 2, 0, buf, 10, &w, &h) == -1, "sprite bitmap: a too-small buffer is refused");
    check(i8244_render_glyph(&v, 5, 1, 0xffffff, 0, buf, sizeof buf / 4, &w, &h) == 0 && w == 8 && h == 8, "glyph bitmap");
    {
        int ok = 1;

        for (int r = 0; r < 8; r++)
            for (int cx = 0; cx < 8; cx++)
                if (((g_font[5 * 8 + r] >> (7 - cx)) & 1) != (buf[r * 8 + cx] == 0xffffff))
                    ok = 0;
        check(ok, "glyph bitmap matches the font bytes");
    }
    check(i8244_render_char(&v, 0, 3, 1, 0, buf, sizeof buf / 4, &w, &h) == 0 && w == 8 && h == s.singles[3].rows,
          "char bitmap: rows follow the pointer");
    check(i8244_render_char(&v, 1, 9, 1, 0, buf, sizeof buf / 4, &w, &h) == 0 && h == s.quads[2].rows, "quad-member bitmap");
    check(i8244_render_font_sheet(&v, 1, 0xffffff, 0, buf, sizeof buf / 4, &w, &h) == 0 && w == 143 && h == 35, "font sheet size");
    check(i8244_render_shape_sheet(&v, 2, 0, buf, sizeof buf / 4, &w, &h) == 0 && w == 70 && h == 16, "shape sheet size");
    check(i8244_render_palette_strip(&v, 4, buf, sizeof buf / 4, &w, &h) == 0 && w == 32 && h == 8 && buf[0] == v.palette[0] &&
          buf[4 * 32] == v.palette[8], "palette strip: 8 dim colours over 8 bright");

    /* layer masks: enable the display and look at what each layer draws */
    i8244_write(&v, 1300, 0xa0, 0);                       /* unlock to set the grid up */
    i8244_write(&v, 1320, 0xa0, 0x20 | 0x08);
    memset(buf, 0, sizeof buf);
    i8244_debug_render(&v, 0, 0, buf, 360, 243);
    {
        int ok = 1;

        for (int i = 0; i < 360 * 243; i++)
            if (buf[i] != 0)
                ok = 0;
        check(ok, "debug render: no layers, nothing drawn");
    }
    i8244_debug_render(&v, I8244_L_BG, 0, buf, 360, 243);
    check(buf[0] == v.palette[s.bg_color] && buf[360 * 242 + 359] == v.palette[s.bg_color], "debug render: background only");
    i8244_debug_render(&v, I8244_L_SPRITES, 0, buf, 360, 243);
    i8244_debug_render(&v, I8244_L_ALL, 0, buf2, 360, 243);
    {
        int sprite_px = 0, only_in_all = 0, other = 0;

        for (int y = 0; y < 243; y++)
            for (int x = 0; x < 360; x++)
            {
                uint32_t c = buf[y * 360 + x];

                if (c == v.palette[8 + 5])
                {
                    sprite_px++;
                    if (x < s.sprites[1].x || x >= s.sprites[1].x + s.sprites[1].width || y < 50 || y >= 82)
                        other++;
                }
                else if (c != 0)
                    other++;
            }
        (void)only_in_all;
        check(sprite_px > 100 && other == 0, "debug render: sprites only draws just the sprite, inside its box");
    }
    i8244_debug_render(&v, I8244_L_ALL, I8244_F_BOXES, buf, 360, 243);
    check(memcmp(buf, buf2, sizeof buf2[0] * 360 * 243) != 0, "debug render: boxes add overlay pixels");
    i8244_write(&v, 1400, 0xa0, 0);                       /* the display off: nothing but the background */
    i8244_debug_render(&v, I8244_L_ALL, 0, buf, 360, 243);
    {
        int bgonly = 1;

        for (int i = 0; i < 360 * 243; i++)
            if (buf[i] != v.palette[s.bg_color])
                bgonly = 0;
        check(bgonly, "debug render: display off draws only the background ...");
    }
    i8244_debug_render(&v, I8244_L_ALL, I8244_F_IGNORE_ENABLE, buf, 360, 243);
    check(memcmp(buf, buf2, sizeof buf2[0] * 360 * 243) == 0, "... unless IGNORE_ENABLE forces objects and grid on (= the enabled picture)");

    /* frame in progress */
    i8244_init(&v, 0, g_font);
    i8244_write(&v, 100, 0xa3, 0x38);                     /* background colour 7 */
    i8244_run_until(&v, tvh(0, 2, 100, 0));
    i8244_catch_up(&v, tvh(0, 2, 100, 200));
    i8244_frame_in_progress(&v, tvh(0, 2, 100, 200), I8244_F_BEAM, buf, &w, &h);
    check(w == 200 && h == 100, "frame in progress: the beam");
    check(buf[50 * 360 + 10] == v.palette[7] && buf[99 * 360 + 359] == v.palette[7],
          "frame in progress: lines done are in colour");
    check(buf[101 * 360 + 10] == ((v.palette[7] & 0xfefefeu) >> 1), "frame in progress: the rest is the previous frame, dimmed");
}

int main(int argc, char **argv)
{
    if (argc > 1 && !strcmp(argv[1], "--replay"))
        return replay_main(argc, argv);

    make_test_font();
    test_t1_and_beam();
    test_events_and_irq();
    test_sound_mix();
    test_cx_and_line_callback();
    test_snapshot_and_helpers();
    for (size_t k = 0; k < sizeof g_golden / sizeof g_golden[0]; k++)
    {
        const i8244_sound_golden_t *snd = NULL;

        for (size_t j = 0; j < sizeof g_sound / sizeof g_sound[0]; j++)
            if ((size_t)g_sound[j].golden == k)
                snd = &g_sound[j];
        run_golden(&g_golden[k], snd);
    }
    printf("%d check(s), %d failure(s)\n", checks, failures);
    return failures ? 1 : 0;
}
