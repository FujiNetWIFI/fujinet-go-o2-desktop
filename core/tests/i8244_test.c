static i8244_t g_chip;

/* MAME's 48 kHz mono output against the C chip's mix of the same register
 * writes: every threshold crossing within 2 samples, and the plateau levels.
 *
 * MAME's sound stream runs at the chip clock (3.58 MHz) and is resampled to
 * 48 kHz, which delays the whole signal by ~3.5 samples (73 us) against the
 * chip's own edge times; the comparison takes that constant out (it is the
 * resampler's, the chip changes its output exactly at the hblank). */
#define MAME_RESAMPLER_LAG2 7   /* 3.5 samples, in half samples */
static int sound_compare(i8244_t *v, const i8244_golden_t *g, const i8244_sound_golden_t *s)
{
    static float out[48000 * 2];
    static int16_t pcm[48000 * 2];
    const double hz = g->pal ? 7093790.0 : 7159090.0;
    uint64_t t_end = (uint64_t)((double)s->nsamples * hz / 48000.0 + 0.5);
    int n = s->nsamples, bad = 0, ce = 0;
    int last_hi = 0;
    int maxdev = 0;

    if (n > 48000 * 2)
        n = 48000 * 2;
    i8244_run_until(v, t_end);
    i8244_sound_mix(v, 0, t_end, out, n);
    for (int i = 0; i < n; i++)
    {
        float f = out[i] * 32768.0f;

        pcm[i] = (int16_t)(f > 32767.f ? 32767 : f);
    }
    /* crossings of the same threshold, in the same order */
    for (int i = 1; i < n; i++)
    {
        int hi = pcm[i] >= s->thr;

        if (i == 1)
            last_hi = pcm[0] >= s->thr;
        if (hi != last_hi)
        {
            if (ce < s->nedges)
            {
                /* in half samples: C's edge plus MAME's lag against MAME's */
                int d = 2 * (i - (int)s->edges[ce]) + MAME_RESAMPLER_LAG2;

                if (d < 0)
                    d = -d;
                if (d > maxdev)
                    maxdev = d;
                if (d > 3)
                {
                    bad++;
                    if (bad < 4)
                        printf("  %s: edge %d at sample %d, MAME %d (+lag)\n", g->name, ce, i, s->edges[ce]);
                }
            }
            ce++;
        }
        last_hi = hi;
    }
    {
        int want = s->nedges;

        if (want == 160)    /* the golden keeps the first 160 */
            ce = ce < 160 ? ce : 160;
        CHECKF(ce == want, "%s: %d edges, MAME %d", g->name, ce, want);
    }
    for (int k = 0; k < s->nprobes; k++)
    {
        int at = s->probe_at[k], m = s->probe_val[k], c = pcm[at];
        int tol = s->peak / 16 + 30;

        if (c - m > tol || m - c > tol)
        {
            bad++;
            printf("  %s: sample %d is %d, MAME %d\n", g->name, at, c, m);
        }
    }
    CHECKF(bad == 0, "%s: sound differs (%d, worst edge deviation %.1f samples)", g->name, bad, maxdev / 2.0);
    return bad;
}

typedef struct {
    const i8244_golden_t *g;
    i8244_t *v;
    uint64_t F;
    int frame;
    int bad_frames;
} gctx_t;

/* publish and check every frame that ends at or before t */
static void frames_until(gctx_t *x, uint64_t t)
{
    while (x->frame < x->g->nframes && (uint64_t)x->frame * x->F <= t)
    {
        i8244_run_until(x->v, (uint64_t)x->frame * x->F);
        if ((uint32_t)frame_hash(x->v->frame) != x->g->hash[x->frame - 1])
        {
            x->bad_frames++;
            printf("  %s: frame %d differs from MAME\n", x->g->name, x->frame);
        }
        x->frame++;
    }
}

static int run_golden(const i8244_golden_t *g, const i8244_sound_golden_t *snd)
{
    const int pal = g->pal;
    gctx_t x;
    uint64_t cyc = 0;
    int adj = 0;
    int reads = 0, bad_reads = 0;
    i8244_t *v = &g_chip;

    x.g = g;
    x.v = v;
    x.F = pal ? 456u * 313u : 455u * 263u;
    x.frame = 1;
    x.bad_frames = 0;
    i8244_init(v, pal, g_font);
    /* MAME applies the chip's timers only after the instruction that runs
     * past them: an access sees the events up to one machine cycle before it */
    i8244_set_access_lag(v, pal ? 18 : 20);

    for (int i = 0; i < g->nstream; i++)
    {
        unsigned w = g->stream[i];
        unsigned op = w >> 12, arg = w & 0xfff;
        uint64_t t;

        switch (op)
        {
        case 0:
            cyc += arg;
            break;
        case 1:
            for (unsigned k = 0; k < arg; k++)
            {
                unsigned d = g->stream[++i];

                cyc += 6;
                t = cyc_to_px(pal, cyc) + (uint64_t)(int64_t)adj;
                adj = 0;
                frames_until(&x, t);
                i8244_write(v, t, d >> 8, (uint8_t)d);
            }
            break;
        case 2:
        {
            unsigned want = g->stream[++i];
            uint8_t got;

            cyc += 4;
            t = cyc_to_px(pal, cyc) + (uint64_t)(int64_t)adj;
            adj = 0;
            frames_until(&x, t);
            got = i8244_read(v, t, arg & 0xff);
            reads++;
            if (got != want)
            {
                bad_reads++;
                printf("  %s: read $%02X at cycle %llu: MAME %02X, C %02X\n", g->name, arg & 0xff,
                       (unsigned long long)cyc, want, got);
            }
            break;
        }
        case 3:
            cyc += 4;
            t = cyc_to_px(pal, cyc);
            frames_until(&x, t);
            i8244_set_p1_lum(v, t, (int)((arg >> 7) & 1));
            break;
        case 4:
            adj = arg == 1 ? 1 : -1;
            break;
        default:
            bad_reads++;
            break;
        }
    }
    frames_until(&x, (uint64_t)g->nframes * x.F);
    CHECKF(bad_reads == 0 && x.bad_frames == 0, "%s: %d bad reads of %d, %d bad frames", g->name, bad_reads, reads,
           x.bad_frames);
    if (snd)
        bad_reads += sound_compare(v, g, snd);
    return bad_reads + x.bad_frames;
}

