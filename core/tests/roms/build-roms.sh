#!/usr/bin/env bash
# Assemble the tests' own 8048 programs (Macroassembler AS: asl + p2bin) into
# core/tests/test_rom.h. The result is committed, so building and testing need
# no assembler; run this only after changing a program here. ASL defaults to
# ~/asl/asl.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
ASL=${ASL:-$HOME/asl/asl}
P2BIN=${P2BIN:-$HOME/asl/p2bin}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
out="$here/../test_rom.h"
{
  echo "/* test_rom.h -- GENERATED by roms/build-roms.sh from roms/*.a48; do not edit."
  echo " * The tests' own 8048 cartridge programs (cartridge window \$400-\$BFF). */"
  echo
} > "$out"
for src in "$here"/*.a48; do
  name=$(basename "$src" .a48)
  cp "$src" "$tmp/$name.a48"
  (cd "$tmp" && "$ASL" -q -cpu 8048 -L "$name.a48" > /dev/null \
     && "$P2BIN" -r 0x400-0x7ff -l 0xff "$name.p" "$name.bin" > /dev/null)
  python3 -I - "$tmp/$name.bin" "$name" >> "$out" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
name = sys.argv[2]
print("static const unsigned char test_rom_%s[%d] = {" % (name, len(data)))
for i in range(0, len(data), 12):
    print("    " + ", ".join("0x%02X" % b for b in data[i:i+12]) + ",")
print("};")
print()
PY
done
echo "wrote $out"
