static uint8_t *fix_image(void)
{
    uint8_t *b = malloc(512);
    for (int i = 0; i < 508; i++) b[i] = (uint8_t)((i % 5) * 3 + 1);
    memcpy(b + 508, fix_tail, 4);
    return b;
}

static uint8_t *dyn_image(void)
{
    static const char *const words[7] = { "odyssey", "videopac", "fujinet", "voice", "speech", "the", "of" };
    uint8_t *b = malloc(2048);
    uint32_t x = 1;
    int n = 0;
    while (n < 2044) {
        const char *w;
        x = x * 1103515245u + 12345u;
        w = words[(x >> 16) % 7];
        for (; *w && n < 2044; w++) b[n++] = (uint8_t)*w;
        if (n < 2044) b[n++] = ' ';
    }
    memcpy(b + 2044, dyn_tail, 4);
    return b;
}

/* ---- sessions -------------------------------------------------------------------- */

static o2session *new_session(const char *tag, char *data, size_t datasz, char *work, size_t worksz)
{
    char cfg[300];
    o2session_paths p;

    test_tmpdir(cfg, sizeof cfg, tag);
    snprintf(data, datasz, "%s/data", cfg);
    snprintf(work, worksz, "%s/in", cfg);
    mkpath(data);
    mkpath(work);
    memset(&p, 0, sizeof p);
    p.config_dir = cfg; p.data_dir = data; p.fujinet_lib = "";
    return o2session_new(&p);
}

static int count_parts(const char *dir)
{
    DIR *d = opendir(dir);
    struct dirent *e;
    int n = 0;
    if (!d) return -1;
    while ((e = readdir(d)) != NULL)
        if (strstr(e->d_name, ".part")) n++;
    closedir(d);
    return n;
}

static int all_available(o2session *s)
{
    for (int i = 0; i < O2_ROM_COUNT; i++)
        if (!o2session_rom_item_available(s, i)) return 0;
    return 1;
}

int main(void)
{
    char data[400], work[400], path[800], dest[900], msg[1024];
    o2session *s;
    uint8_t *buf;
    long n;
    int i, rc;

    crc_tables();
    check(crc_of((const uint8_t *)"123456789", 9) == 0xcbf43926u, "the test's CRC-32 is the standard one");
    check(zipread_crc32((const uint8_t *)"123456789", 9) == 0xcbf43926u, "and so is the reader's");

    /* ---- the table ---- */
    s = new_session("rom1", data, sizeof data, work, sizeof work);
    if (!s) return 1;
    check(o2session_rom_item_count() == O2_ROM_COUNT && O2_ROM_COUNT == 7, "seven ROM items");
    for (i = 0; i < O2_ROM_COUNT; i++) {
        const o2_rom_item *it = o2session_rom_item(i);
        char what[96];
        snprintf(what, sizeof what, "item %d is %s, %u bytes, CRC %08x", i, k_items[i].file,
                 (unsigned)k_items[i].size, (unsigned)k_items[i].crc);
        check(it && !strcmp(it->file, k_items[i].file) && it->size == k_items[i].size
              && it->crc == k_items[i].crc && it->name && it->group, what);
    }
    check(o2session_rom_item(-1) == NULL && o2session_rom_item(O2_ROM_COUNT) == NULL, "no item out of range");
    check(!strcmp(o2session_rom_item(O2_ROM_BIOS)->group, "Console")
          && !strcmp(o2session_rom_item(O2_ROM_FONT_8244)->group, "Video chips")
          && !strcmp(o2session_rom_item(O2_ROM_VOICE_SPEECH)->group, "The Voice"),
          "grouped for the Preferences list");
    check(strncmp(o2session_roms_path(s), data, strlen(data)) == 0, "the ROM directory is under the data tree");
    for (i = 0; i < O2_MACHINE_COUNT; i++)
        if (o2session_have_bios(s, i) || o2session_have_font(s, i)) break;
    check(i == O2_MACHINE_COUNT && !o2session_have_voice(s) && !all_available(s),
          "nothing is imported yet");

    /* ---- one file, any name ---- */
    snprintf(path, sizeof path, "%s/Magnavox Odyssey 2 BIOS (1978).bin", work);
    write_item(path, O2_ROM_BIOS, 1);
    check(o2session_media_is_rom(path), "a BIOS dump is recognised as a ROM by size and CRC");
    rc = o2session_rom_import(s, path, msg, sizeof msg);
    check(rc == 1, "importing it takes one item");
    check(strstr(msg, "o2bios.rom") != NULL && strstr(msg, "next power cycle") != NULL, "and says what and when");
    snprintf(dest, sizeof dest, "%s/o2bios.rom", o2session_roms_path(s));
    check(size_of(dest) == 1024, "it is stored as MAME's o2bios.rom");
    buf = read_all(dest, &n);
    check(n == 1024 && crc_of(buf, 1024) == 0x8016a315u, "byte for byte");
    free(buf);
    check(count_parts(o2session_roms_path(s)) == 0, "with no .part file left behind");
    check(o2session_have_bios(s, O2_MACHINE_ODYSSEY2) && o2session_have_bios(s, O2_MACHINE_VIDEOPAC),
          "the Odyssey 2 and the G7000 share it");
    check(!o2session_have_bios(s, O2_MACHINE_VIDEOPAC_PLUS), "the G7400 does not");
    check(o2session_rom_item_available(s, O2_ROM_BIOS) && !o2session_rom_item_available(s, O2_ROM_FONT_8244),
          "the item list says so");

    /* a BIOS under another name is still the BIOS (MAME's own other name) */
    snprintf(path, sizeof path, "%s/o2rom.bin", work);
    write_item(path, O2_ROM_BIOS, 2);
    check(o2session_rom_import(s, path, msg, sizeof msg) == 1, "o2rom.bin is the BIOS too");
    check(count_parts(o2session_roms_path(s)) == 0 && size_of(dest) == 1024, "importing twice is harmless");

    /* ---- every item ---- */
    for (i = 0; i < O2_ROM_COUNT; i++) {
        char name[600], what[160];
        snprintf(name, sizeof name, "%s/dump-%d.dat", work, i);
        write_item(name, i, 100 + (uint32_t)i);
        rc = o2session_rom_import(s, name, msg, sizeof msg);
        snprintf(dest, sizeof dest, "%s/%s", o2session_roms_path(s), k_items[i].file);
        snprintf(what, sizeof what, "%s imports under its own name", k_items[i].file);
        check(rc == 1 && size_of(dest) == (long)k_items[i].size && o2session_rom_item_available(s, i), what);
    }
    check(all_available(s), "all seven are in the ROM directory");
    check(o2session_have_bios(s, O2_MACHINE_VIDEOPAC_PLUS) && o2session_have_font(s, O2_MACHINE_VIDEOPAC_PLUS)
          && o2session_have_font(s, O2_MACHINE_ODYSSEY2) && o2session_have_voice(s),
          "every machine has what it needs");

    /* ---- the G7400 is not complete without its font and its BIOS ---- */
    o2session_free(s);
    s = new_session("rom2", data, sizeof data, work, sizeof work);
    snprintf(path, sizeof path, "%s/font.bin", work);
    write_item(path, O2_ROM_FONT_8244, 5);
    check(o2session_rom_import(s, path, msg, sizeof msg) == 1, "the 8244 font imports");
    check(o2session_have_font(s, O2_MACHINE_ODYSSEY2) && o2session_have_font(s, O2_MACHINE_VIDEOPAC)
          && !o2session_have_font(s, O2_MACHINE_VIDEOPAC_PLUS),
          "it is the Odyssey 2's and the G7000's character set; the G7400 needs the EF9340's too");
    snprintf(path, sizeof path, "%s/ef.rom", work);
    write_item(path, O2_ROM_FONT_EF9340, 6);
    rc = o2session_rom_import(s, path, msg, sizeof msg);
    check(rc == 1 && o2session_have_font(s, O2_MACHINE_VIDEOPAC_PLUS), "the EF9340's completes the G7400's");
    check(strstr(msg, "bad dump") != NULL && strstr(msg, "datasheet") != NULL,
          "with MAME's bad-dump warning in the message");
    check(!o2session_have_bios(s, O2_MACHINE_VIDEOPAC_PLUS), "the G7400 still has no BIOS");
    snprintf(path, sizeof path, "%s/g7400.bin", work);
    write_item(path, O2_ROM_BIOS_G7400, 7);
    check(o2session_rom_import(s, path, msg, sizeof msg) == 1 && o2session_have_bios(s, O2_MACHINE_VIDEOPAC_PLUS),
          "its own BIOS makes the G7400");
    check(!o2session_have_bios(s, O2_MACHINE_ODYSSEY2), "which is not the Odyssey 2's");

    /* The Voice needs the SP0256's ROM and the speech ROM; Sid's is its own */
    snprintf(path, sizeof path, "%s/v1.bin", work);
    write_item(path, O2_ROM_VOICE_INTERNAL, 8);
    o2session_rom_import(s, path, msg, sizeof msg);
    check(!o2session_have_voice(s), "the SP0256's ROM alone is not a Voice");
    snprintf(path, sizeof path, "%s/v2.bin", work);
    write_item(path, O2_ROM_VOICE_SPEECH, 9);
    o2session_rom_import(s, path, msg, sizeof msg);
    check(o2session_have_voice(s) && !o2session_rom_item_available(s, O2_ROM_VOICE_SID),
          "with the speech ROM it is; Sid's is separate");

    /* ---- recognised, not stored ---- */
    o2session_free(s);
    s = new_session("rom3", data, sizeof data, work, sizeof work);
    {
        static const struct { const char *file; uint32_t crc; } unused[3] = {
            { "c52.rom", 0xa318e8d6u }, { "jopac.bin", 0x11647ca5u }, { "odyssey3.bin", 0xe2b23324u },
        };
        for (i = 0; i < 3; i++) {
            uint8_t *b = malloc(1024);
            char what[96];
            forge(b, 1024, 40 + (uint32_t)i, unused[i].crc);
            snprintf(path, sizeof path, "%s/%s", work, unused[i].file);
            write_file(path, b, 1024);
            free(b);
            check(o2session_media_is_rom(path), "a dump of another console is still recognised as a ROM");
            rc = o2session_rom_import(s, path, msg, sizeof msg);
            snprintf(what, sizeof what, "%s: recognised, not used by this version, nothing stored", unused[i].file);
            check(rc == 0 && strstr(msg, unused[i].file) != NULL && strstr(msg, "not used by this version") != NULL
                  && count_parts(o2session_roms_path(s)) == 0 && !o2session_have_bios(s, O2_MACHINE_ODYSSEY2), what);
        }
        check(!exists(o2session_roms_path(s)) || !all_available(s), "the ROM directory has none of them");
    }

    /* ---- an unknown dump of the BIOS's size ---- */
    {
        uint8_t unknown[1024];
        for (i = 0; i < 1024; i++) unknown[i] = (uint8_t)(i * 7 + 3);
        check(crc_of(unknown, 1024) != 0x8016a315u, "the filler is not the BIOS");

        /* alone in a folder: never guessed */
        snprintf(path, sizeof path, "%s/sweep", work);
        mkpath(path);
        snprintf(dest, sizeof dest, "%s/unknown.bin", path);
        write_file(dest, unknown, 1024);
        rc = o2session_rom_import(s, path, msg, sizeof msg);
        check(rc == 0 && !o2session_have_bios(s, O2_MACHINE_ODYSSEY2), "a folder sweep does not take an unknown 1 KB file");
        check(strstr(msg, "No Odyssey 2") != NULL, "and says nothing was found");

        /* in a zip: never guessed */
        {
            zent z[1];
            z[0] = stored_bytes("mystery.bin", unknown, 1024);
            snprintf(dest, sizeof dest, "%s/mystery.zip", work);
            write_zip(dest, z, 1);
            check(!o2session_media_is_rom(dest), "a zip of unknowns is not a ROM zip");
            rc = o2session_rom_import(s, dest, msg, sizeof msg);
            check(rc == 0 && !o2session_have_bios(s, O2_MACHINE_ODYSSEY2), "nor is an unknown file in a zip");
        }

        /* as a dropped file: not a ROM either (a cartridge may be 1 KB) */
        snprintf(path, sizeof path, "%s/patched.bin", work);
        write_file(path, unknown, 1024);
        check(!o2session_media_is_rom(path), "a dropped unknown 1 KB file is left for the cartridge path");

        /* the one file the user hands over: taken, with a warning */
        rc = o2session_rom_import(s, path, msg, sizeof msg);
        check(rc == 1 && o2session_have_bios(s, O2_MACHINE_ODYSSEY2), "handed over alone it is taken as the BIOS");
        check(strstr(msg, "CRC-32") != NULL && strstr(msg, "o2bios.rom") != NULL,
              "with a warning naming its CRC");
        {
            char want[16];
            snprintf(want, sizeof want, "%08X", (unsigned)crc_of(unknown, 1024));
            check(strstr(msg, want) != NULL, "the CRC is the file's");
        }
        snprintf(dest, sizeof dest, "%s/o2bios.rom", o2session_roms_path(s));
        buf = read_all(dest, &n);
        check(n == 1024 && memcmp(buf, unknown, 1024) == 0, "stored as o2bios.rom");
        free(buf);

        /* a file of any other size is not a ROM at all */
        {
            uint8_t odd[1000];
            memset(odd, 0x55, sizeof odd);
            snprintf(path, sizeof path, "%s/odd.bin", work);
            write_file(path, odd, sizeof odd);
            rc = o2session_rom_import(s, path, msg, sizeof msg);
            check(rc == 0 && strstr(msg, "1000 bytes") != NULL && strstr(msg, "odd.bin") != NULL,
                  "a 1000-byte file is refused, with its size");
            check(!o2session_media_is_rom(path), "and is not a ROM");
        }
        /* nor is a right-sized file of the wrong content (512 bytes, not the font's CRC) */
        {
            uint8_t wrong[512];
            memset(wrong, 0xaa, sizeof wrong);
            snprintf(path, sizeof path, "%s/wrong.bin", work);
            write_file(path, wrong, sizeof wrong);
            rc = o2session_rom_import(s, path, msg, sizeof msg);
            check(rc == 0 && !o2session_rom_item_available(s, O2_ROM_FONT_8244),
                  "a 512-byte file that is not the character set is refused (only the BIOS is ever guessed)");
        }
    }

    /* ---- a zip, stored: MAME's videopac.zip has a subfolder inside ---- */
    o2session_free(s);
    s = new_session("rom4", data, sizeof data, work, sizeof work);
    {
        zent z[3];
        uint8_t other[100];
        memset(other, 3, sizeof other);
        z[0] = stored_item("o2bios.rom", O2_ROM_BIOS, 11);
        z[1] = stored_item("videopacf/c52.rom", O2_ROM_BIOS, 12);  /* same bytes as a BIOS: counts as the BIOS */
        z[2] = stored_bytes("readme.txt", other, sizeof other);
        snprintf(dest, sizeof dest, "%s/videopac.zip", work);
        write_zip(dest, z, 3);
        check(o2session_media_is_rom(dest), "a zip with a ROM in it is a ROM");
        rc = o2session_rom_import(s, dest, msg, sizeof msg);
        check(rc == 1 && o2session_have_bios(s, O2_MACHINE_ODYSSEY2), "the stored zip's BIOS is imported");
        free_stored();

        /* three ROMs in one zip, and a duplicate counted once */
        z[0] = stored_item("charset_i8244.bin", O2_ROM_FONT_8244, 13);
        z[1] = stored_item("spr128-003.bin", O2_ROM_VOICE_SPEECH, 14);
        z[2] = stored_item("sub/dir/also-the-font.bin", O2_ROM_FONT_8244, 15);
        snprintf(dest, sizeof dest, "%s/mix.zip", work);
        write_zip(dest, z, 3);
        rc = o2session_rom_import(s, dest, msg, sizeof msg);
        check(rc == 2 && o2session_have_font(s, O2_MACHINE_ODYSSEY2)
              && o2session_rom_item_available(s, O2_ROM_VOICE_SPEECH), "a zip of several: two distinct items");
        check(strstr(msg, "charset_i8244.bin") != NULL && strstr(msg, "spr128-003.bin") != NULL,
              "the message names them");
        free_stored();
    }

    /* ---- a zip, deflated: fixed and dynamic Huffman ---- */
    o2session_free(s);
    s = new_session("rom5", data, sizeof data, work, sizeof work);
    {
        uint8_t *fi = fix_image(), *di = dyn_image();
        uint8_t out[2048];
        zent z[2];

        check(crc_of(fi, 512) == 0xb46a3f31u && crc_of(di, 2048) == 0x4bb43724u,
              "the fixtures decompress to ROMs of the importer's table");
        check(zipread_inflate(fix_stream, sizeof fix_stream, out, 512) == 0 && memcmp(out, fi, 512) == 0,
              "inflate: the fixed-Huffman stream");
        check(zipread_inflate(dyn_stream, sizeof dyn_stream, out, 2048) == 0 && memcmp(out, di, 2048) == 0,
              "inflate: the dynamic-Huffman stream");
        check(zipread_inflate(dyn_stream, sizeof dyn_stream - 20, out, 2048) != 0, "inflate: a truncated stream fails");
        check(zipread_inflate(dyn_stream, sizeof dyn_stream, out, 2047) != 0, "inflate: output over the stated size fails");
        check(zipread_inflate(dyn_stream, sizeof dyn_stream, out, 2049) != 0, "inflate: output short of the stated size fails");
        {
            uint8_t bad[sizeof dyn_stream];
            memcpy(bad, dyn_stream, sizeof bad);
            bad[0] |= 6;           /* block type 3 is invalid */
            check(zipread_inflate(bad, sizeof bad, out, 2048) != 0, "inflate: a reserved block type fails");
        }
        {   /* a stored block: BFINAL=1 BTYPE=0, LEN=5, NLEN=~5, "hello" */
            static const uint8_t st[] = { 0x01, 0x05, 0x00, 0xfa, 0xff, 'h', 'e', 'l', 'l', 'o' };
            check(zipread_inflate(st, sizeof st, out, 5) == 0 && !memcmp(out, "hello", 5), "inflate: a stored block");
        }

        z[0].name = "charset_i8244.bin"; z[0].data = fix_stream; z[0].csize = sizeof fix_stream;
        z[0].usize = 512; z[0].crc = 0xb46a3f31u; z[0].method = 8;
        z[1].name = "sp0256b-019.bin"; z[1].data = dyn_stream; z[1].csize = sizeof dyn_stream;
        z[1].usize = 2048; z[1].crc = 0x4bb43724u; z[1].method = 8;
        snprintf(dest, sizeof dest, "%s/deflated.zip", work);
        write_zip(dest, z, 2);
        check(o2session_media_is_rom(dest), "a deflated zip is recognised");
        rc = o2session_rom_import(s, dest, msg, sizeof msg);
        check(rc == 2, "both deflated entries import");
        snprintf(path, sizeof path, "%s/charset_i8244.bin", o2session_roms_path(s));
        buf = read_all(path, &n);
        check(n == 512 && memcmp(buf, fi, 512) == 0, "the fixed-Huffman entry, byte for byte");
        free(buf);
        snprintf(path, sizeof path, "%s/sp0256b-019.bin", o2session_roms_path(s));
        buf = read_all(path, &n);
        check(n == 2048 && memcmp(buf, di, 2048) == 0, "the dynamic-Huffman entry, byte for byte");
        free(buf);

        /* a corrupt entry (CRC wrong) is skipped, not imported */
        z[0].crc = 0x12345678u;
        snprintf(dest, sizeof dest, "%s/corrupt.zip", work);
        write_zip(dest, z, 1);
        o2session_free(s);
        s = new_session("rom5b", data, sizeof data, work, sizeof work);
        snprintf(dest, sizeof dest, "%s/corrupt.zip", work);
        write_zip(dest, z, 1);
        rc = o2session_rom_import(s, dest, msg, sizeof msg);
        check(rc == 0 && !o2session_rom_item_available(s, O2_ROM_FONT_8244), "a zip entry whose CRC is wrong is not imported");
        free(fi);
        free(di);
    }

    /* ---- a folder, eight levels deep, with zips in it ---- */
    o2session_free(s);
    s = new_session("rom6", data, sizeof data, work, sizeof work);
    {
        char deep[600];
        snprintf(deep, sizeof deep, "%s/pile", work);
        for (i = 0; i < 8; i++) {
            char seg[16];
            snprintf(seg, sizeof seg, "/d%d", i);
            strcat(deep, seg);
        }
        mkpath(deep);
        snprintf(path, sizeof path, "%s/o2bios.rom", deep);
        write_item(path, O2_ROM_BIOS, 21);                       /* 8 levels down: found */
        snprintf(path, sizeof path, "%s/pile/d0/d1/readme.txt", work);
        write_file(path, "hi", 2);
        snprintf(path, sizeof path, "%s/pile/d0/font.bin", work);
        write_item(path, O2_ROM_FONT_8244, 22);                  /* one level down */

        strcat(deep, "/d8");
        mkpath(deep);
        snprintf(path, sizeof path, "%s/g7400.bin", deep);
        write_item(path, O2_ROM_BIOS_G7400, 23);                 /* 9 levels down: not found */

        {
            zent z[1];
            z[0] = stored_item("sp0256b-019.bin", O2_ROM_VOICE_INTERNAL, 24);
            snprintf(path, sizeof path, "%s/pile/d0/d1/voice.zip", work);
            write_zip(path, z, 1);                               /* a zip inside the folder */
            free_stored();
        }
        snprintf(path, sizeof path, "%s/pile", work);
        check(!o2session_media_is_rom(path), "a folder is not itself a dropped ROM");
        rc = o2session_rom_import(s, path, msg, sizeof msg);
        check(rc == 3, "the folder: the BIOS 8 levels down, the font, the zip's Voice ROM");
        check(o2session_have_bios(s, O2_MACHINE_ODYSSEY2) && o2session_have_font(s, O2_MACHINE_ODYSSEY2)
              && o2session_rom_item_available(s, O2_ROM_VOICE_INTERNAL), "all three are there");
        check(!o2session_rom_item_available(s, O2_ROM_BIOS_G7400), "the one 9 levels down is not");
        check(strstr(msg, "o2bios.rom") && strstr(msg, "charset_i8244.bin") && strstr(msg, "sp0256b-019.bin"),
              "the message names what it found");

        /* the import_media route: a dropped ROM goes to the ROM directory */
        snprintf(path, sizeof path, "%s/pile/d0/font.bin", work);
        check(o2session_import_media(s, path, dest, sizeof dest) == 0
              && strstr(dest, "charset_i8244.bin") != NULL, "a dropped ROM is routed to the ROM directory");
        snprintf(path, sizeof path, "%s/pile/d0/d1/voice.zip", work);
        check(o2session_import_media(s, path, dest, sizeof dest) == 0
              && strcmp(dest, "") != 0, "so is a dropped zip of ROMs");
    }

    /* ---- nothing there, and nothing to read ---- */
    o2session_free(s);
    s = new_session("rom7", data, sizeof data, work, sizeof work);
    snprintf(path, sizeof path, "%s/none", work);
    mkpath(path);
    rc = o2session_rom_import(s, path, msg, sizeof msg);
    check(rc == 0 && msg[0], "an empty folder: nothing recognised, and it says so");
    snprintf(path, sizeof path, "%s/does-not-exist", work);
    rc = o2session_rom_import(s, path, msg, sizeof msg);
    check(rc == -1 && strstr(msg, "does-not-exist") != NULL, "a missing path is an error");
    check(strstr(o2session_last_error(s), "does-not-exist") != NULL, "and the session's error says so too");
    check(o2session_rom_import(s, "", msg, sizeof msg) == -1 && o2session_rom_import(s, NULL, msg, sizeof msg) == -1,
          "an empty path is an error");
    check(!o2session_media_is_rom(path) && !o2session_media_is_rom(NULL) && !o2session_media_is_rom(""),
          "none of them is a ROM");
    snprintf(path, sizeof path, "%s/notazip.zip", work);
    write_file(path, "PK this is not really a zip, whatever it is called", 51);
    check(o2session_rom_import(s, path, msg, sizeof msg) == 0, "a file called .zip that is not one is just a file");

    /* ---- O2_ROM_DIR moves the ROM directory (the tests' own override) ---- */
    {
        char alt[600], cfg[300];
        o2session_paths p;
        o2session *s2;

        test_tmpdir(cfg, sizeof cfg, "rom8");
        snprintf(alt, sizeof alt, "%s/elsewhere/roms", cfg);
#if defined(_WIN32)
        _putenv_s("O2_ROM_DIR", alt);
#else
        setenv("O2_ROM_DIR", alt, 1);
#endif
        snprintf(data, sizeof data, "%s/data", cfg);
        memset(&p, 0, sizeof p);
        p.config_dir = cfg; p.data_dir = data; p.fujinet_lib = "";
        s2 = o2session_new(&p);
        check(s2 && strcmp(o2session_roms_path(s2), alt) == 0, "O2_ROM_DIR is the ROM directory");
        snprintf(path, sizeof path, "%s/bios.bin", cfg);
        write_item(path, O2_ROM_BIOS, 31);
        if (s2) {
            check(o2session_rom_import(s2, path, msg, sizeof msg) == 1, "an import lands there");
            snprintf(dest, sizeof dest, "%s/o2bios.rom", alt);
            check(size_of(dest) == 1024 && o2session_have_bios(s2, O2_MACHINE_ODYSSEY2), "and is found there");
            o2session_free(s2);
        }
#if defined(_WIN32)
        _putenv_s("O2_ROM_DIR", "");
#else
        unsetenv("O2_ROM_DIR");
#endif
    }

    o2session_free(s);
    printf("%d failure(s)\n", failures);
    return failures ? 1 : 0;
}
