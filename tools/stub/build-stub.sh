#!/usr/bin/env bash
# Assemble core/o2/stub.a48 (Macro Assembler AS: asl + p2bin) and write the
# image as core/o2/stub.c. Prints the byte count. Needs ASL (default ~/asl).
set -euo pipefail
here=$(cd "$(dirname "$0")/../.." && pwd)
ASL=${ASL:-$HOME/asl/asl}
P2BIN=${P2BIN:-$HOME/asl/p2bin}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cp "$here/core/o2/stub.a48" "$tmp/stub.a48"
(cd "$tmp" && "$ASL" -q -cpu 8048 -L stub.a48 >/dev/null && "$P2BIN" -q -r 0x000-0x3ff stub.p stub.bin)
python3 -I - "$tmp/stub.bin" "$here/core/o2/stub.c" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
assert len(data) == 0x400, len(data)
lines = ["/* stub.c -- GENERATED by tools/stub/build-stub.sh from stub.a48; do not edit.",
         " * The no-BIOS stand-in: the reset/interrupt vectors, readkey and getjoystick. */",
         "",
         '#include "o2_internal.h"',
         "",
         "const uint8_t o2_stub[O2_STUB_SIZE] = {"]
for i in range(0, len(data), 12):
    chunk = data[i:i+12]
    lines.append("    " + ", ".join("0x%02X" % b for b in chunk) + ",")
lines.append("};")
open(sys.argv[2], "w").write("\n".join(lines) + "\n")
print("stub: %d bytes" % len(data))
PY
