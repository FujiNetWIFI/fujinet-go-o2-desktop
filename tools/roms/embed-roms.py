#!/usr/bin/env python3
"""Generate roms_embedded.c: the recognised ROM images in a directory, or
nothing at all.

The Odyssey 2 / Videopac BIOS, the video chips' character sets and The
Voice's speech ROMs are copyrighted firmware and are not redistributed by
this project (COMPLIANCE.md). --none is therefore the SHIPPING configuration,
not an error path: it emits an empty table, and the machine boots CONFIG on
the app's own stand-in.

With a directory (WITH_O2_ROMS=ON, a developer build), every file in it --
and every entry of every zip in it, so MAME's videopac.zip, i8244.zip and
videopacp.zip can be dropped in as they are -- whose size and CRC-32 match
MAME's table (the same table as core/src/roms.c) is embedded under MAME's
file name, whatever it is called locally. Anything else is ignored.

usage: embed-roms.py <out.c> <dir>
       embed-roms.py --none <out.c>
"""

import sys
import zipfile
import zlib
from pathlib import Path

# (size, crc) -> MAME's file name; mirrors s_items[] in core/src/roms.c (the
# dumps of consoles this version does not emulate are not embedded)
KNOWN = {
    (0x400, 0x8016A315): "o2bios.rom",             # Odyssey 2 / Videopac G7000
    (0x400, 0xE20A9F41): "g7400.bin",              # Videopac+ G7400
    (0x200, 0xB46A3F31): "charset_i8244.bin",      # 8244/8245 character set
    (0xA00, 0x8DE85988): "charset_ef9340_1.rom",   # EF9340 character set
    (0x800, 0x4BB43724): "sp0256b-019.bin",        # The Voice: SP0256 mask ROM
    (0x4000, 0x509367B5): "spr128-003.bin",        # The Voice: speech ROM
    (0x4000, 0xE79DFB75): "spr128-004.bin",        # Sid the Spellbinder's speech
}
MAX_SIZE = 0x4000

HEADER = """/* Generated by tools/roms/embed-roms.py -- do not edit.
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
#include "roms_embedded.h"

"""


def candidates(src):
    """Every file in the directory, and every entry of every zip in it."""
    for f in sorted(src.iterdir()) if src.is_dir() else []:
        if not f.is_file():
            continue
        if zipfile.is_zipfile(f):
            with zipfile.ZipFile(f) as z:
                for info in z.infolist():
                    if not info.is_dir() and info.file_size <= MAX_SIZE:
                        yield z.read(info)
        elif f.stat().st_size <= MAX_SIZE:
            yield f.read_bytes()


def main():
    args = sys.argv[1:]
    if args and args[0] == "--none":
        if len(args) != 2:
            sys.exit(__doc__)
        Path(args[1]).write_text(
            HEADER
            + "/* Nothing embedded -- the shipping configuration. */\n"
            + "const o2_embedded_rom o2_embedded_roms[1] = { { 0, 0, 0 } };\n"
            + "const unsigned o2_embedded_rom_count = 0;\n")
        return 0

    if len(args) != 2:
        sys.exit(__doc__)
    out, src = Path(args[0]), Path(args[1])
    found = {}
    for data in candidates(src):
        name = KNOWN.get((len(data), zlib.crc32(data) & 0xFFFFFFFF))
        if name and name not in found:
            found[name] = data

    body = [HEADER,
            "/* WITH_O2_ROMS=ON: a developer build. NOT redistributable.\n"
            " * See COMPLIANCE.md. */\n"]
    for i, (name, data) in enumerate(found.items()):
        body.append("static const uint8_t rom%d[%d] = {\n" % (i, len(data)))
        for j in range(0, len(data), 16):
            body.append("    " + ",".join("0x%02X" % b for b in data[j:j + 16]) + ",\n")
        body.append("};\n")
    body.append("\nconst o2_embedded_rom o2_embedded_roms[%d] = {\n" % max(1, len(found)))
    for i, (name, data) in enumerate(found.items()):
        body.append('    { "%s", rom%d, %d },\n' % (name, i, len(data)))
    if not found:
        body.append("    { 0, 0, 0 },\n")
    body.append("};\nconst unsigned o2_embedded_rom_count = %d;\n" % len(found))
    out.write_text("".join(body))
    print("embed-roms: %d image(s): %s" % (len(found), ", ".join(found) or "none"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
