#!/usr/bin/env python3
"""gen_fuzz.py -- writes fuzz.a48, the random-instruction probe.

    tools/ab/probes/gen_fuzz.py > tools/ab/probes/fuzz.a48

About 500 random instructions (a fixed seed, so the output is reproducible) in
the cartridge's $400-$7FF, run forty times over from a loop in the ROM so the
registers and flags wander. The instruction mix is every family that is safe
to scramble: the accumulator and register ops, flags, rotates, DA, XCH / XCHD,
the timer (STRT T, MOV T,A, MOV A,T, EN / DIS TCNTI, JTF) with its interrupt
(a bare RETR), the port and BUS reads and writes, the expander, MOVP / MOVP3,
and forward conditional jumps that stay in their page. R0 and R1 are the
pointers for @R0 / @R1 and only ever hold $20-$3B; R6 is the loop counter.

SPDX-License-Identifier: GPL-3.0-or-later
"""

import random

SEED = 20261101
COUNT = 500
REGS = ("r2", "r3", "r4", "r5")        # the data registers the code may write


def main():
    rnd = random.Random(SEED)
    lines = []

    def byte():
        return "0%02Xh" % rnd.randrange(256)

    rr = lambda: rnd.choice(("r0", "r1", "r2", "r3", "r4", "r5", "r7"))   # readable
    wr = lambda: rnd.choice(REGS)                                         # writable
    ind = lambda: rnd.choice(("@r0", "@r1"))
    jcc = ("jc", "jnc", "jz", "jnz", "jf0", "jf1", "jb0", "jb1", "jb2", "jb3", "jb4",
           "jb5", "jb6", "jb7", "jtf", "jt0", "jnt0")

    def gen():
        """One instruction as (text, length), or ('jcc', mnemonic) for a jump."""
        k = rnd.randrange(100)
        if k < 8:
            return ("%s a,#%s" % (rnd.choice(("add", "addc", "anl", "orl", "xrl")), byte()), 2)
        if k < 16:
            return ("%s a,%s" % (rnd.choice(("add", "addc", "anl", "orl", "xrl")), rr()), 1)
        if k < 22:
            return ("%s a,%s" % (rnd.choice(("add", "addc", "anl", "orl", "xrl")), ind()), 1)
        if k < 27:
            return ("mov a,#%s" % byte(), 2)
        if k < 31:
            return ("mov %s,#%s" % (wr(), byte()), 2)
        if k < 33:
            return ("mov %s,#%s" % (rnd.choice(("r0", "r1")), "0%02Xh" % rnd.randrange(0x20, 0x3C)), 2)
        if k < 36:
            return ("mov %s,#%s" % (ind(), byte()), 2)
        if k < 40:
            return ("mov a,%s" % rr(), 1)
        if k < 43:
            return ("mov %s,a" % wr(), 1)
        if k < 46:
            return ("mov a,%s" % ind(), 1)
        if k < 48:
            return ("mov %s,a" % ind(), 1)
        if k < 51:
            return ("xch a,%s" % rnd.choice(REGS + ("@r0", "@r1")), 1)
        if k < 53:
            return ("xchd a,%s" % ind(), 1)
        if k < 57:
            return ("%s %s" % (rnd.choice(("inc", "dec")), wr()), 1)
        if k < 59:
            return ("inc %s" % ind(), 1)
        if k < 66:
            return (rnd.choice(("inc a", "dec a", "clr a", "cpl a", "swap a", "rl a", "rr a", "rlc a",
                                "rrc a", "da a")), 1)
        if k < 70:
            return (rnd.choice(("clr c", "cpl c", "clr f0", "cpl f0", "clr f1", "cpl f1")), 1)
        if k < 73:
            return ("mov a,psw", 1)
        if k < 79:
            return (rnd.choice(("strt t", "stop tcnt", "mov a,t", "mov t,a", "en tcnti", "dis tcnti")), 1)
        if k < 82:
            return (rnd.choice(("in a,p1", "in a,p2", "ins a,bus", "outl bus,a", "outl p1,a",
                                "outl p2,a")), 1)
        if k < 84:
            return ("%s %s,#%s" % (rnd.choice(("orl", "anl")), rnd.choice(("p1", "p2", "bus")), byte()), 2)
        if k < 87:
            port = "p%d" % rnd.randrange(4, 8)
            return (rnd.choice(("movd a,%s", "movd %s,a", "orld %s,a", "anld %s,a")) % port, 1)
        if k < 89:
            return (rnd.choice(("movp a,@a", "movp3 a,@a")), 1)
        return ("jcc", rnd.choice(jcc))

    # the program: a list of (text, length); a jump is (None, mnemonic) and fixed up later
    prog = []
    for _ in range(COUNT):
        text, ln = gen()
        prog.append((text, ln))

    # addresses from $400, then forward jumps whose operand byte and target share a page
    addr = 0x400
    where = []
    for text, ln in prog:
        where.append(addr)
        addr += 2 if text == "jcc" else ln
    end = addr
    assert end < 0x7F0, "the block runs into the end of the page: lower COUNT"

    out = []
    out.append("; fuzz.a48 -- GENERATED by gen_fuzz.py (seed %d): %d random instructions in the" % (SEED, COUNT))
    out.append("; cartridge, forty passes over them. See the generator for the instruction mix.")
    out.append("; FRAMES: 20")
    out.append('    include "common.inc"')
    out.append("")
    out.append("start:")
    out.append("    mov r0,#30h")
    out.append("    mov r1,#34h")
    out.append("    mov r2,#3Ch")
    out.append("    mov r3,#0C5h")
    out.append("    mov r4,#17h")
    out.append("    mov r5,#0A9h")
    out.append("    mov r6,#40")
    out.append("    mov r7,#0")
    out.append("    mov a,#5Bh")
    out.append("    mov @r0,a")
    out.append("    mov a,#0E2h")
    out.append("    mov @r1,a")
    out.append("    mov a,#81h")
    out.append("again:")
    out.append("    jmp 400h")
    out.append("")
    out.append("loopctl:")
    out.append("    djnz r6,again")
    out.append("    jmp finish")
    out.append("")
    out.append("    org 3D0h")
    out.append("xint:")
    out.append("    retr")
    out.append("tint:")
    out.append("    retr")
    out.append('    include "common_end.inc"')
    out.append("")
    out.append("    org 400h")

    skipped = 0
    for i, (text, ln) in enumerate(prog):
        out.append("f%d:" % i)
        if text != "jcc":
            out.append("    " + text)
            continue
        # a conditional jump forward by 1-4 instructions, within the operand's page
        mnemonic = ln
        operand_page = (where[i] + 1) >> 8
        target = None
        for ahead in rnd.sample((1, 2, 3, 4), 4):
            j = i + ahead
            if j < len(prog) and (where[j] >> 8) == operand_page:
                target = j
                break
        if target is None:
            out.append("    nop")           # (the jump's two bytes)
            out.append("    nop")
            skipped += 1
        else:
            out.append("    %s f%d" % (mnemonic, target))
    out.append("f%d:" % len(prog))
    out.append("    jmp loopctl")
    print("\n".join(out))


if __name__ == "__main__":
    main()
