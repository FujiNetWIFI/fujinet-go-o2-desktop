#!/usr/bin/env python3
"""config_golden.py -- regenerate core/tests/config_golden.h from MAME.

    config_golden.py [--frames N] [--at 40,100,...] > core/tests/config_golden.h

Runs MAME (odyssey2, `-cartslot fujinet`, the link down) on the baked CONFIG
client with THIS repository's no-BIOS stand-in as the BIOS and the generated
test font (o2ab.test_font) as the 8244's character set -- so the picture
needs no copyrighted ROM -- dumps every frame through tools/ab/vdc_log.lua and
prints the FNV-1a hash of the colour words of the chosen frames. The test
core/tests/config_frames_test.c boots the same machine in our core and must
reproduce every hash: CONFIG exercises the 8048, the interrupts, the lazy
raster renderer (it rewrites the objects per text row from a counter
interrupt) and the cartridge's APPBANK serving, all against MAME.

Needs MAME with the FujiNet O2 cartridge device (fujinet-firmware's
pico/o2/emu/apply-mame.sh) and the staged firmware headers
(core/o2/fuji-generated/fujiconfigrom.h: configure the project first).
"""
import argparse
import os
import re
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import o2ab  # noqa: E402


def c_array(path):
    text = open(path).read()
    body = text[text.index("{", text.index("[")) :]
    return bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", body))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--frames", type=int, default=450)
    ap.add_argument("--at", default="40,100,160,220,300,400")
    args = ap.parse_args()
    at = [int(x) for x in args.at.split(",")]

    work = tempfile.mkdtemp(prefix="o2cfg-")
    romdir = o2ab.make_romdir(os.path.join(work, "roms"))
    os.makedirs(os.path.join(romdir, "videopac"))
    open(os.path.join(romdir, "videopac", "o2bios.rom"), "wb").write(
        c_array(os.path.join(ROOT, "core/o2/stub.c")))
    cfg = os.path.join(work, "config.bin")
    open(cfg, "wb").write(
        c_array(os.path.join(ROOT, "core/o2/fuji-generated/fujiconfigrom.h")))
    raw = os.path.join(work, "frames.raw")
    o2ab.run_mame(cfg, os.path.join(HERE, "vdc_log.lua"),
                  {"VDC_LOG": os.path.join(work, "vdc.log"), "VDC_FRAMES": raw,
                   "VDC_FRAMES_N": args.frames, "FUJINET_TCP": "127.0.0.1:9"},
                  args.frames / 59 + 3, romdir, extra=("-cartslot", "fujinet"),
                  timeout=180)
    data = open(raw, "rb").read()
    fsz = o2ab.W * o2ab.H * 4
    n = len(data) // fsz
    if n < max(at) + 1:
        raise SystemExit("MAME produced only %d frames" % n)
    print("/* config_golden.h -- GENERATED by tools/ab/config_golden.py from MAME;")
    print(" * the FNV-1a (64-bit) hash of the 0x00RRGGBB words of CONFIG's frames on the")
    print(" * stand-in BIOS with the generated test font, link down. Do not edit. */")
    print("")
    print("static const struct { int frame; unsigned long long hash; } k_config_golden[] = {")
    for f in at:
        px = data[f * fsz:(f + 1) * fsz]
        h = 14695981039346656037
        for i in range(0, fsz, 4):
            h ^= int.from_bytes(px[i:i + 3], "little")
            h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
        print("    { %d, 0x%016xull }," % (f, h))
    print("};")


if __name__ == "__main__":
    main()
