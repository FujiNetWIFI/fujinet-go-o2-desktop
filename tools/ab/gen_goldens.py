#!/usr/bin/env python3
"""gen_goldens.py -- make core/tests/i8244_golden.h from MAME.

    gen_goldens.py [--out core/tests/i8244_golden.h] [--work DIR] [--only NAME[,NAME]] [-j N]

For every scene (scenes.py, specials.py) it builds a test cart, runs MAME
(odyssey2, or videopac for PAL) headless with the real BIOS and the generated
TEST FONT, logs every VDC access with its time (vdc_log.lua) and the frame
MAME leaves, checks that the cart did exactly what the cart model says, and
records:

  * the access stream (compact, see the encoding below) with the values MAME
    returned for every read,
  * the low 32 bits of a hash of each frame (FNV-1a 64 over the XRGB words, i8244_test.c's
    frame_hash()).

i8244_test.c replays the stream into the C chip and requires the same reads
and the same frame hashes.  No ROM is needed to run it, and none is written
here: the font is a formula (o2ab.test_font()).

Stream encoding (uint16 words, times in 8048 machine cycles):
  0x0nnn   DELAY n cycles
  0x1nnn   RUN n: the next n words are (offset << 8 | data) VDC writes, each
           one 6 cycles after the previous access (or the DELAY before it)
  0x2ooo   READ offset ooo: the next word is the value MAME returned; 4 cycles
  0x3ppp   P1 write (value ppp & 0xff; the cart does `mov a,#v; outl p1,a`),
           4 cycles; only bit 7 (LUM) matters to the chip
  0x4001 / 0x4002   the next access is 1 pixel clock later / earlier than the
           cycle count says (MAME's time fell on the other side of a rounding
           tie; the cycle -> pixel conversion is i8244_test.c's cyc_to_px())

Requires MAME (~/Workspace/mame), asl/p2bin (~/asl), the real BIOS in MAME's
rompath.  The BIOS hands over to the cart at cycle ~16 without touching the
VDC, so the C replay starts from the power-on state.
"""
import argparse, concurrent.futures, os, shutil, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import o2ab, o2cart, scenes
from abrun import *

REPO = os.path.abspath(os.path.join(HERE, "..", ".."))


def build_scene_cart(sc):
    cart = o2cart.Cart(pal=sc.pal)
    cart.marker_cycle = MARKER_CYCLE
    F = frame_px(sc.pal)
    if sc.lum == 0:
        cart.p1_set(o2cart.P1_VDC)
    cart.at(int(F * 1.15))
    for a, v in sc.writes:
        cart.w(a, v)
    for a in sc.readback_addrs:
        cart.r(a)
    cart.w(0xa3, sc.color)
    cart.w(0xa2, sc.mask)
    cart.w(0xa0, sc.control)
    if sc.probes:
        cart.at(int(F * (sc.settle_frames + 0.4)))
        for a in sc.probes:
            cart.r(a)
    return cart


def do_scene(sc, work):
    cart = build_scene_cart(sc)
    cart.name = sc.name
    return result_for(sc.name, cart, sc.pal, sc.frames, work)


def emit_header(path, results):
    out = []
    out.append("/* i8244_golden.h -- GENERATED by tools/ab/gen_goldens.py from MAME; do not edit.\n"
               " *\n"
               " * Each case is a cart's VDC access stream (encoding in gen_goldens.py) with the values MAME\n"
               " * returned for the reads, and MAME's frame hash after each frame (FNV-1a 64 over the XRGB\n"
               " * words).  MAME ran with the generated test font (o2ab.test_font()), not the real charset.\n"
               " * The MAME run's access log is the only input: no ROM data is in here.\n"
               " */\n")
    out.append("typedef struct {\n    const char *name;\n    int pal;\n    int nframes;       /* frames MAME ran */\n"
               "    const uint16_t *stream;\n    int nstream;\n    const uint32_t *hash;  /* low 32 bits of the frame hash, frames 1..nframes-1 */\n} i8244_golden_t;\n")
    for k, r in enumerate(results):
        w = r["stream"]
        out.append("static const uint16_t g_s%d[] = {" % k)
        line = ""
        for x in w:
            tok = "%d," % x
            if len(line) + len(tok) > 118:
                out.append(line)
                line = ""
            line += tok
        out.append(line)
        out.append("};")
        out.append("static const uint32_t g_h%d[] = {%s};" % (k, ", ".join("0x%08x" % (h & 0xffffffff) for h in r["hashes"])))
    out.append("\nstatic const i8244_golden_t g_golden[] = {")
    for k, r in enumerate(results):
        out.append('    { "%s", %d, %d, g_s%d, %d, g_h%d },' % (r["name"], 1 if r["pal"] else 0, r["nframes"], k,
                                                             len(r["stream"]), k))
    out.append("};")
    out.append("""
/* MAME's 48 kHz output for the cases that make sound: `edges` are the sample indices where the
 * signal crosses `thr` (half its peak), `probe` samples are plateau values (int16) away from edges. */
typedef struct {
    int golden;            /* index into g_golden */
    int nsamples, thr, peak;
    const uint16_t *edges; int nedges;
    const uint16_t *probe_at; const int16_t *probe_val; int nprobes;
} i8244_sound_golden_t;
""")
    snd = [(k, r) for k, r in enumerate(results) if "sound" in r]
    for k, r in snd:
        sd = r["sound"]
        out.append("static const uint16_t g_e%d[] = {%s};" % (k, ", ".join(str(e) for e in sd["edges"]) or "0"))
        out.append("static const uint16_t g_pa%d[] = {%s};" % (k, ", ".join(str(p[0]) for p in sd["probes"]) or "0"))
        out.append("static const int16_t g_pv%d[] = {%s};" % (k, ", ".join(str(p[1]) for p in sd["probes"]) or "0"))
    out.append("static const i8244_sound_golden_t g_sound[] = {")
    for k, r in snd:
        sd = r["sound"]
        out.append("    { %d, %d, %d, %d, g_e%d, %d, g_pa%d, g_pv%d, %d }, /* %s */" % (
            k, sd["nsamples"], sd["thr"], sd["peak"], k, len(sd["edges"]), k, k, len(sd["probes"]), r["name"]))
    out.append("};")
    open(path, "w").write("\n".join(out) + "\n")


def all_cases():
    from specials import special_cases
    cs = [("scene", s) for s in scenes.build_scenes()]
    cs += [("special", s) for s in special_cases()]
    return cs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(REPO, "core", "tests", "i8244_golden.h"))
    ap.add_argument("--work", default=os.path.join(os.environ.get("TMPDIR", "/tmp"), "i8244-ab"))
    ap.add_argument("--only")
    ap.add_argument("-j", type=int, default=4)
    a = ap.parse_args()
    os.makedirs(a.work, exist_ok=True)
    o2ab.make_romdir(os.path.join(a.work, "roms_test"))
    cases = all_cases()
    if a.only:
        want = set(a.only.split(","))
        cases = [c for c in cases if c[1].name in want]
    t0 = time.time()

    def go(c):
        kind, s = c
        try:
            return do_scene(s, a.work) if kind == "scene" else s.run(a.work)
        except SystemExit as e:
            return ("FAIL", s.name, str(e))

    with concurrent.futures.ThreadPoolExecutor(a.j) as ex:
        res = list(ex.map(go, cases))
    bad = [r for r in res if isinstance(r, tuple)]
    for b in bad:
        print("FAIL", b[1], b[2])
    if bad:
        return 1
    emit_header(a.out, res)
    print("%d cases, %d reads, %d words, %.0fs -> %s" % (len(res), sum(r['reads'] for r in res),
                                                      sum(len(r['stream']) for r in res), time.time() - t0, a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
